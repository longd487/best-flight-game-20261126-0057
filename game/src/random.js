// Seeded randomness for Ridge Runner. The world, the rings and the clouds
// all come from one seed, so the same seed always builds the same valley
// and the same screenshots always show the same frame.

/** Mulberry32: a small, fast seeded PRNG. */
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** A tiny hash of two integers, stable across runs. */
function hash2(ix, iz, seed) {
  let h = (ix * 374761393 + iz * 668265263 + seed * 974634211) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return (((h ^ (h >>> 16)) >>> 0) / 4294967296);
}

function smooth(t) {
  return t * t * (3 - 2 * t);
}

/**
 * One-dimensional value noise: smooth bumps between -1 and 1, seeded.
 * Used for the valley's wandering centreline and the ridge heights.
 */
export function noise1(x, seed) {
  const ix = Math.floor(x);
  const fx = x - ix;
  const a = hash2(ix, 0, seed) * 2 - 1;
  const b = hash2(ix + 1, 0, seed) * 2 - 1;
  return a + (b - a) * smooth(fx);
}

/**
 * Two-dimensional value noise, seeded. Used for field patchwork and
 * the lumps on the mountainsides.
 */
export function noise2(x, z, seed) {
  const ix = Math.floor(x);
  const iz = Math.floor(z);
  const fx = x - ix;
  const fz = z - iz;
  const a = hash2(ix, iz, seed) * 2 - 1;
  const b = hash2(ix + 1, iz, seed) * 2 - 1;
  const c = hash2(ix, iz + 1, seed) * 2 - 1;
  const d = hash2(ix + 1, iz + 1, seed) * 2 - 1;
  const u = smooth(fx);
  const v = smooth(fz);
  return a + (b - a) * u + (c - a) * v + (a - b - c + d) * u * v;
}

/** Clamp a value into a range. */
export function clamp(v, lo, hi) {
  return v < lo ? lo : v > hi ? hi : v;
}

/** Linear interpolation. */
export function lerp(a, b, t) {
  return a + (b - a) * t;
}

/** Smoothstep between two edges. */
export function smoothstep(edge0, edge1, x) {
  const t = clamp((x - edge0) / (edge1 - edge0), 0, 1);
  return t * t * (3 - 2 * t);
}
